#!/usr/bin/env python3
"""Generate small synthetic edge-case videos with FFmpeg into data/sample/.

    python scripts/make_synthetic_samples.py [--force]

These are generated test fixtures, not real content: they exercise the
pipeline's handling of missing modalities, very short clips and corrupt files.
Writes data/sample/manifest.csv. Existing files are kept unless --force.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from hookline import paths  # noqa: E402
from hookline.manifest import format_bool, write_manifest  # noqa: E402
from hookline.media import STATUS_OK, probe_video  # noqa: E402

W, H, FPS = 540, 960, 30
SOURCE = "synthetic: generated by scripts/make_synthetic_samples.py"
LICENSE = "generated by project; no third-party content"
FONT_CANDIDATES = (
    "/System/Library/Fonts/Supplemental/Arial.ttf",
    "/System/Library/Fonts/Helvetica.ttc",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "C:/Windows/Fonts/arial.ttf",
)
ENC_V = ["-c:v", "libx264", "-preset", "veryfast", "-crf", "30", "-pix_fmt", "yuv420p"]
ENC_A = ["-c:a", "aac", "-b:a", "64k"]


def font_opt() -> str:
    font = next((f for f in FONT_CANDIDATES if Path(f).exists()), None)
    return f"fontfile='{font}':" if font else ""


def text(label: str, start: float, end: float, size: int = 64, y: str = "(h-text_h)/2") -> str:
    return (
        f"drawtext={font_opt()}text='{label}':fontcolor=white:fontsize={size}:"
        f"x=(w-text_w)/2:y={y}:enable='between(t,{start},{end})'"
    )


def specs() -> list[dict]:
    lavfi = ["-f", "lavfi", "-i"]
    pattern = f"testsrc2=size={W}x{H}:rate={FPS}"
    return [
        {
            "id": "syn_av_testpattern_8s",
            "notes": "moving test pattern + 440 Hz tone; baseline audio+video",
            "args": lavfi + [f"{pattern}:duration=8"] + lavfi + ["sine=frequency=440:duration=8"] + ENC_V + ENC_A + ["-shortest"],
        },
        {
            "id": "syn_silent_no_audio_stream_6s",
            "notes": "video only, no audio stream (silent video without text)",
            "args": lavfi + [f"{pattern}:duration=6"] + ENC_V + ["-an"],
        },
        {
            "id": "syn_silent_audio_track_5s",
            "notes": "audio stream present but digitally silent",
            "args": lavfi + [f"{pattern}:duration=5"] + lavfi + ["anullsrc=channel_layout=stereo:sample_rate=44100"] + ENC_V + ENC_A + ["-t", "5"],
        },
        {
            "id": "syn_text_slides_9s",
            "notes": "text-led slideshow: three text cards, no audio",
            "args": lavfi + [f"color=c=0x1d3557:size={W}x{H}:rate={FPS}:duration=9"]
            + ["-vf", ",".join([text("Slide 1 - The hook", 0, 3), text("Slide 2 - The point", 3, 6), text("Slide 3 - Payoff", 6, 9)])]
            + ENC_V + ["-an"],
        },
        {
            "id": "syn_static_image_tone_7s",
            "notes": "static image with pulsing tone; audio-led, no visual motion",
            "args": lavfi + [f"color=c=0x6a040f:size={W}x{H}:rate={FPS}:duration=7"] + lavfi
            + ["sine=frequency=220:duration=7"]
            + ["-vf", text("Static frame", 0, 7, 72), "-af", "volume='0.5+0.5*sin(2*PI*t)':eval=frame"]
            + ENC_V + ENC_A + ["-shortest"],
        },
        {
            "id": "syn_low_quality_visual_audio_6s",
            "notes": "dark, noisy, low-res upscaled visuals with clear audio",
            "args": lavfi + ["testsrc2=size=144x256:rate=15:duration=6"] + lavfi + ["sine=frequency=660:duration=6"]
            + ["-vf", f"scale={W // 2}:{H // 2}:flags=neighbor,eq=brightness=-0.35,noise=alls=30:allf=t", "-r", "15"]
            + ENC_V + ENC_A + ["-shortest"],
        },
        {
            "id": "syn_very_short_0p4s",
            "notes": "0.4 s clip; below minimum useful duration",
            "args": lavfi + [f"{pattern}:duration=0.4"] + lavfi + ["sine=frequency=880:duration=0.4"] + ENC_V + ENC_A + ["-shortest"],
        },
        {
            "id": "syn_audio_only_5s",
            "notes": "MP4 with audio stream only, no video stream",
            "args": lavfi + ["sine=frequency=330:duration=5"] + ENC_A + ["-vn"],
        },
    ]


def ffmpeg_run(ffmpeg: str, args: list[str], out: Path) -> None:
    cmd = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y"] + args + [str(out)]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg failed for {out.name}: {proc.stderr.strip()[-400:]}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", type=Path, default=paths.sample_dir())
    parser.add_argument("--force", action="store_true", help="regenerate existing files")
    args = parser.parse_args()

    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        print("ERROR: ffmpeg not found. Install it (macOS: brew install ffmpeg) and retry.", file=sys.stderr)
        return 1
    out_dir: Path = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    entries: list[tuple[str, Path, str]] = []
    for spec in specs():
        out = out_dir / f"{spec['id']}.mp4"
        if args.force or not out.exists():
            print(f"generating {out.name}")
            ffmpeg_run(ffmpeg, spec["args"], out)
        entries.append((spec["id"], out, spec["notes"]))

    # Corrupt fixtures derived from our own baseline file (moov atom is at the end, so truncation breaks it).
    baseline = out_dir / "syn_av_testpattern_8s.mp4"
    truncated = out_dir / "syn_corrupt_truncated.mp4"
    if args.force or not truncated.exists():
        data = baseline.read_bytes()
        truncated.write_bytes(data[: len(data) // 3])
    entries.append(("syn_corrupt_truncated", truncated, "first third of a valid MP4; container index missing"))
    empty = out_dir / "syn_corrupt_zero_bytes.mp4"
    if args.force or not empty.exists():
        empty.write_bytes(b"")
    entries.append(("syn_corrupt_zero_bytes", empty, "empty file"))

    rows = []
    for vid, path, notes in entries:
        probe = probe_video(path)
        readable = probe.status == STATUS_OK
        rows.append(
            {
                "video_id": vid,
                "file_path": path.name,
                "duration_seconds": probe.duration_seconds if readable else "",
                "has_audio": format_bool(probe.has_audio if readable else None),
                "has_video": format_bool(probe.has_video if readable else None),
                "source": SOURCE,
                "license_or_permission": LICENSE,
                "dataset_split": "fixture",
                "notes": notes if readable else f"{notes}; probe: {probe.error}",
            }
        )
        detail = probe.error if not readable else f"{probe.duration_seconds}s audio={probe.has_audio} video={probe.has_video}"
        print(f"  {vid}: {probe.status} {detail}")
    manifest = write_manifest(out_dir / "manifest.csv", rows)
    print(f"Wrote {manifest} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
