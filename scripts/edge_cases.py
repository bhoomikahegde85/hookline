#!/usr/bin/env python3
"""Run the whole pipeline on tricky inputs and record what the system does with each (no crash, a clear reason, partial results where possible).

    python scripts/edge_cases.py --allow-remote                 # synthetic fixtures + generated landscape / long / no-audio clips, through run_e2e
    python scripts/edge_cases.py --allow-remote --only syn_silent_no_audio_stream_6s long_75s

Each input goes through the same one-command pipeline as the upload page (features, speech and text, TTCC on your Space, scores, explanation, review page).
The synthetic fixtures are generated by this project (no third-party content), so nothing company-owned is uploaded. Results: 01-Hookline/evaluation/edge_cases/<timestamp>/
(edge_cases.json and edge_cases.md). A failure is a finding, not an error: what matters is that it is reported clearly and that earlier results survive.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import subprocess
import sys
import time
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT / "src"))

from hookline.app_server import Job  # noqa: E402
from hookline.views_eval import new_run_dir, now_stamp  # noqa: E402

FIXTURES = PROJECT_ROOT / "data" / "sample"
NOTES = {
    "syn_av_testpattern_8s": "moving pattern with a tone: the happy path on a short clip",
    "syn_silent_no_audio_stream_6s": "no audio stream at all",
    "syn_silent_audio_track_5s": "audio stream present but silent",
    "syn_text_slides_9s": "text-led slideshow, no speech",
    "syn_static_image_tone_7s": "one static image with a tone",
    "syn_low_quality_visual_audio_6s": "dark, low-quality picture and noisy audio",
    "syn_very_short_0p4s": "0.4 s clip, below the model's 5 s minimum",
    "syn_audio_only_5s": "audio only, no video stream",
    "syn_corrupt_truncated": "first third of a valid MP4 (corrupt)",
    "syn_corrupt_zero_bytes": "empty file",
    "landscape_10s": "16:9 landscape, 10 s",
    "long_75s": "75 s clip: more than one TTCC window",
    "no_audio_12s": "12 s portrait clip, video only",
}


def generate(out: Path) -> dict[str, Path]:
    """Extra clips that are not in the fixtures: landscape, a long one, and a portrait clip without audio."""
    out.mkdir(parents=True, exist_ok=True)
    enc = ["-c:v", "libx264", "-pix_fmt", "yuv420p", "-preset", "veryfast"]
    spec = {"landscape_10s": ("testsrc2=s=960x540:r=25:d=10", ["-f", "lavfi", "-i", "sine=frequency=330:duration=10", "-c:a", "aac", "-shortest"]),
            "long_75s": ("testsrc2=s=540x960:r=25:d=75", ["-f", "lavfi", "-i", "sine=frequency=220:duration=75", "-c:a", "aac", "-shortest"]),
            "no_audio_12s": ("testsrc2=s=540x960:r=25:d=12", ["-an"])}
    paths = {}
    for name, (src, audio) in spec.items():
        p = out / f"{name}.mp4"
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", src, *audio, *enc, str(p)], check=True)
        paths[name] = p
    return paths


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--allow-remote", action="store_true", help="required: clips are uploaded to your TTCC Space (they are synthetic, not company reels)")
    ap.add_argument("--only", nargs="*", help="run only these case names")
    ap.add_argument("--hook-s", type=int, default=10)
    ap.add_argument("--data", type=Path, default=PROJECT_ROOT / "01-Hookline")
    args = ap.parse_args(argv)
    if not args.allow_remote:
        ap.error("--allow-remote is required")
    spec = importlib.util.spec_from_file_location("run_e2e", PROJECT_ROOT / "scripts" / "run_e2e.py")
    e2e = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(e2e)
    run_dir = new_run_dir(args.data / "evaluation" / "edge_cases", now_stamp())
    cases = {p.stem: p for p in sorted(FIXTURES.glob("syn_*.mp4"))} | generate(PROJECT_ROOT / "artifacts" / "edge_inputs")  # outside 01-Hookline/: synthetic, not company data
    if args.only:
        cases = {k: v for k, v in cases.items() if k in args.only}
    results = []
    for name, path in cases.items():
        job = Job(name, path, {})
        t0 = time.time()
        code = e2e.run_e2e(path, run_dir / "artifacts", run=subprocess.run, log=job.add, allow_remote=True, approve=None, siglip=True, skip_local=False,
                           open_page=False, gemini=False, gemini_allow_remote=False, hook_s=args.hook_s, full_curve=True)
        steps = [{"name": s["name"][:60], "state": s["state"], "detail": s["detail"][:120]} for s in job.view()["steps"]]
        at = next((i for i, ln in enumerate(job.log) if ": FAILED" in ln), None)
        reason = " ".join(ln.strip() for ln in job.log[at + 1: at + 5] if ln.strip() and not ln.strip().startswith(("summary", "outputs"))) if at is not None else ""
        page = (run_dir / "artifacts" / "features" / name / "review.html").is_file()
        results.append({"case": name, "note": NOTES.get(name, ""), "exit_code": code, "seconds": round(time.time() - t0, 1), "review_page": page, "steps": steps, "reason": reason[:400],
                        "last_lines": [ln.strip()[:200] for ln in job.log[-6:]]})
        print(f"{name}: exit {code}, review page {'yes' if page else 'no'}, {results[-1]['seconds']} s", flush=True)
    (run_dir / "edge_cases.json").write_text(json.dumps(results, indent=2))
    rows = ["| case | what it tests | result | review page | stopped at |", "|---|---|---|---|---|"]
    for r in results:
        failed = next((s for s in r["steps"] if s["state"] == "failed"), None)
        rows.append(f"| {r['case']} | {r['note']} | {'ok' if r['exit_code'] == 0 else 'stopped'} | {'yes' if r['review_page'] else 'no'} | "
                    f"{(failed['name'] + ' - ' + r['reason'][:260]) if failed else ''} |")
    (run_dir / "edge_cases.md").write_text("\n".join(rows) + "\n")
    (run_dir.parent / "LATEST").write_text(run_dir.name + "\n")
    print(f"results: {run_dir / 'edge_cases.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
